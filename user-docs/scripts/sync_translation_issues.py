"""Keeps the translation issues in line with translation_status.py.

One tracking issue "User docs translations" and one sub-issue per locale ("Translate the user docs into Spanish (es_ES)",
label `translation`) whose task list has one task per section, checked when the section is current. Idempotent:
creates what is missing, rewrites bodies that changed, closes a locale issue when everything is current and
reopens it when something is missing or stale again. Needs `gh` (GH_TOKEN in Actions).

  python3 user-docs/scripts/sync_translation_issues.py --dry-run     print what would change, write nothing
  python3 user-docs/scripts/sync_translation_issues.py               apply (default repo Catrobat/Catroweb, or $GITHUB_REPOSITORY)
"""
import json
import os
import re
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import check  # noqa: E402
import translation_status  # noqa: E402

REPO = os.environ.get("GITHUB_REPOSITORY", "Catrobat/Catroweb")
LABEL = "translation"
TRACKING = "User docs translations"
GUIDE = f"https://github.com/{REPO}/blob/main/user-docs/TRANSLATING.md"
FOOTER = "<!-- Generated by user-docs/scripts/sync_translation_issues.py after every merge to main. Edits to this text are overwritten. -->"


def gh(*args):
    """Run gh; --jq '.[]' output is one JSON value per line, anything else is one JSON document."""
    out = subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout
    if "--jq" in args:
        return [json.loads(line) for line in out.splitlines() if line.strip()]
    return json.loads(out) if out.strip() else None


def write(*args):
    """gh for a call that changes something, paced for GitHub's secondary rate limit on content changes."""
    time.sleep(1)
    return gh(*args)


def languages():
    lines = (check.ROOT / "locales.txt").read_text(encoding="utf-8").splitlines()
    return dict(line.split(maxsplit=1) for line in lines if line.strip() and not line.startswith("#"))


def todo(files):
    return len(files["missing"]) + len(files["stale"]) + len(files["reviewed-stale"])


def locale_body(locale, language, sections):
    lines = [
        f"Translate the Catrobat docs into {language} (`{locale}`). Pick an unchecked task (a comment that you take it is welcome, not required), "
        f"follow [TRANSLATING.md]({GUIDE}) and open one pull request per task, titled like the task and mentioning this issue.",
        "",
    ]
    for section, files in sections.items():
        parts = [f"{len(files[s])} {s}" for s in translation_status.STATES[:3] if files[s]]
        lines.append(f"- [{' ' if parts else 'x'}] `{locale}: {section}`" + (f": {', '.join(parts)}" if parts else ""))
    lines += ["", f"Details: `python3 user-docs/scripts/translation_status.py {locale}`", "", FOOTER]
    return "\n".join(lines)


def tracking_body(status):
    lines = [
        "The docs are translated by volunteers with their own AI assistant, one pull request per task. "
        f"Each language has a sub-issue with its tasks. How it works: [TRANSLATING.md]({GUIDE}).",
        "",
        "| Locale | Sections done | Pages current |",
        "| --- | --- | --- |",
    ]
    for locale, sections in status.items():
        done = sum(1 for files in sections.values() if not todo(files))
        current = translation_status.counts(sections)["current"]
        total = sum(len(f) for files in sections.values() for f in files.values())
        lines.append(f"| `{locale}` | {done}/{len(sections)} | {current}/{total} |")
    lines += ["", FOOTER]
    return "\n".join(lines)


def main(argv):
    dry = "--dry-run" in argv
    status = translation_status.status()
    names = languages()
    issues = gh("api", "--paginate", f"repos/{REPO}/issues?state=all&labels={LABEL}&per_page=100", "--jq", ".[] | select(.pull_request == null)")
    # Locale issues are found by the "(<locale>)" at the end of the title, so a renamed language updates its issue.
    by_key = {}
    for issue in issues:
        match = re.search(r"\(([^()]+)\)$", issue["title"])
        by_key.setdefault(TRACKING if issue["title"] == TRACKING else match and match.group(1), issue)
    changes = {"create": 0, "update": 0, "close": 0, "reopen": 0, "link": 0, "unchanged": 0}

    def ensure(key, title, body, closed):
        """Create or update one issue; returns it (None in a dry run that would create it)."""
        issue = by_key.get(key)
        if issue is None:
            changes["create"] += 1
            print(f"create  {title}" + (" (then close: nothing to do)" if closed else ""))
            if dry:
                return None
            issue = write("api", f"repos/{REPO}/issues", "-f", f"title={title}", "-f", f"body={body}", "-f", f"labels[]={LABEL}")
        fields = []
        if issue["title"] != title or issue.get("body") != body:
            fields += ["-f", f"title={title}", "-f", f"body={body}"]
        state = "closed" if closed else "open"
        if issue["state"] != state:
            fields += ["-f", f"state={state}"] + (["-f", "state_reason=completed"] if closed else [])
        if not fields:
            changes["unchanged"] += 1
            return issue
        if key in by_key:
            action = "update" if issue["state"] == state else "close" if closed else "reopen"
            changes[action] += 1
            print(f"{action:7} {title}")
        if not dry:
            issue = write("api", "-X", "PATCH", f"repos/{REPO}/issues/{issue['number']}", *fields)
        return issue

    if not dry:
        subprocess.run(["gh", "label", "create", LABEL, "--repo", REPO, "--color", "0e8a16", "--force",
                        "--description", "Translating the user docs (user-docs/) into another language"], check=True, capture_output=True)
    tracking = ensure(TRACKING, TRACKING, tracking_body(status), closed=False)
    linked = set()
    if tracking is not None:
        linked = {i["id"] for i in gh("api", "--paginate", f"repos/{REPO}/issues/{tracking['number']}/sub_issues?per_page=100", "--jq", ".[]")}
    for locale, sections in status.items():
        title = f"Translate the user docs into {names[locale]} ({locale})"
        issue = ensure(locale, title, locale_body(locale, names[locale], sections), closed=not any(todo(f) for f in sections.values()))
        if issue is None or issue["id"] not in linked:
            changes["link"] += 1
            if not dry:
                write("api", f"repos/{REPO}/issues/{tracking['number']}/sub_issues", "-F", f"sub_issue_id={issue['id']}")
    for key, issue in by_key.items():
        if key != TRACKING and key not in status:
            print(f"note    labelled {LABEL} but not a locale in locales.txt, left alone: #{issue['number']} {issue['title']}")
    print(("dry run: " if dry else "") + ", ".join(f"{v} {k}" for k, v in changes.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
