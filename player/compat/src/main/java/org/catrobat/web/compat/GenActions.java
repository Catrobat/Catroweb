package org.catrobat.web.compat;

import org.objectweb.asm.ClassReader;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.MethodNode;

import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Enumeration;
import java.util.HashMap;
import java.util.Map;
import java.util.TreeSet;
import java.util.zip.ZipEntry;
import java.util.zip.ZipFile;

/**
 * Writes ActionRegistry.java: Actions.registerAction(X.class, X::new) for every concrete scene2d Action in Catroid,
 * because the web backend cannot create pooled actions by reflection. Usage: GenActions catroid.jar gdx.jar out.java
 */
public final class GenActions {
	public static void main(String[] args) throws Exception {
		Map<String, String> superOf = new HashMap<>();
		Map<String, ClassNode> catroid = new HashMap<>();
		for (int i = 0; i < 2; i++) {
			try (ZipFile zip = new ZipFile(args[i])) {
				for (Enumeration<? extends ZipEntry> e = zip.entries(); e.hasMoreElements(); ) {
					ZipEntry entry = e.nextElement();
					if (!entry.getName().endsWith(".class")) {
						continue;
					}
					try (InputStream in = zip.getInputStream(entry)) {
						ClassNode node = new ClassNode();
						new ClassReader(in).accept(node, ClassReader.SKIP_CODE);
						superOf.put(node.name, node.superName);
						if (0 == i) {
							catroid.put(node.name, node);
						}
					}
				}
			}
		}

		TreeSet<String> actions = new TreeSet<>();
		for (ClassNode node : catroid.values()) {
			boolean concrete = 0 == (node.access & (Opcodes.ACC_ABSTRACT | Opcodes.ACC_INTERFACE)) && 0 != (node.access & Opcodes.ACC_PUBLIC)
					&& !node.name.contains("$") || (null != node.outerClass && 0 != (node.access & Opcodes.ACC_STATIC));
			boolean noArgs = node.methods.stream().anyMatch(m -> "<init>".equals(m.name) && "()V".equals(m.desc) && 0 != (m.access & Opcodes.ACC_PUBLIC));
			if (concrete && noArgs && isAction(node.name, superOf)) {
				actions.add(node.name.replace('/', '.').replace('$', '.'));
			}
		}

		StringBuilder out = new StringBuilder();
		out.append("package org.catrobat.web;\n\n");
		out.append("import com.badlogic.gdx.scenes.scene2d.actions.Actions;\n\n");
		out.append("/** Generated by compat/GenActions from Catroid's classes; do not edit. */\n");
		out.append("final class ActionRegistry {\n\tprivate ActionRegistry() {\n\t}\n\n\tstatic void registerAll() {\n");
		for (String action : actions) {
			out.append("\t\tActions.registerAction(").append(action).append(".class, ").append(action).append("::new);\n");
		}
		out.append("\t}\n}\n");
		Files.writeString(Path.of(args[2]), out);
		System.out.println(actions.size() + " actions registered");
	}

	private static boolean isAction(String name, Map<String, String> superOf) {
		for (String c = name; null != c; c = superOf.get(c)) {
			if ("com/badlogic/gdx/scenes/scene2d/Action".equals(c)) {
				return true;
			}
		}
		return false;
	}
}
