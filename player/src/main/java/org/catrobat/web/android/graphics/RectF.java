package org.catrobat.web.android.graphics;

/** android.graphics.RectF for the bubble's rounded box. */
public class RectF {
	public float left;
	public float top;
	public float right;
	public float bottom;

	public RectF(float left, float top, float right, float bottom) {
		this.left = left;
		this.top = top;
		this.right = right;
		this.bottom = bottom;
	}
}
